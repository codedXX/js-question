/**
 * 假设：
 * 旧列表：A, B, C, D, E
 * 新列表：A, C, D, B, E
 * (注意：仅仅是把 B 挪到了 D 的后面)
 * 
 * --- Vue 2 的计算过程 ---
 * 1. 【头头比】：A == A，不用动。旧头和新头都往后走。
 *    (剩下 旧: B,C,D,E / 新: C,D,B,E)
 * 2. 【尾尾比】：E == E，不用动。旧尾和新尾都往前走。
 *    (剩下 旧: B,C,D / 新: C,D,B)
 * 3. 头头、尾尾都对不上。开始【头尾比】：发现 旧头(B) == 新尾(B)！
 *    说明 B 被挪到了最后面。执行 DOM 移动：把 B 挪到 D 的后面。
 * 4. 剩下的 C 和 D 按顺序比对成功。结束。
 * 
 * --- Vue 3 的计算过程 ---
 * 1. 【掐头去尾】：从前往后比，A一样跳过；从后往前比，E一样跳过。
 *    (瞬间剥离出真正乱序的部分：旧 [B, C, D] / 新 [C, D, B])
 * 2. 【找相对位置不变的标杆】：计算新序列在旧序列中的位置索引，
 *    C 排第2，D 排第3，B 排第1 -> 得到位置数组 [2, 3, 1]。
 * 3. 【最长递增子序列】：在 [2, 3, 1] 中，递增的序列是 [2, 3] (对应 C 和 D)。
 *    说明 C 和 D 相对位置没变，它们站着别动！
 *    只有 B 不在序列里，只需执行一次 DOM 移动：把 B 挪到 D 的后面。结束。
 * 
 * --- 💡 为什么 Vue 3 更好？ ---
 * 在这个简单的例子里，两者都只移动了一次 B。但是想象一下，如果列表中间有 1000 个元素被完全打乱了：
 * 
 * - Vue 2 会用 4 个指针在两端疯狂循环试探，如果这 4 种情况都没中，还要拿着新元素去旧列表里遍历查找，计算量非常大。
 * - Vue 3 则直接通过数组索引映射，瞬间算出一个“最长递增子序列”。比如算出有 800 个元素相对位置没变，那这 800 个 DOM 直接不动，只挪另外 200 个。计算速度和 DOM 操作效率都实现了降维打击。
 * 
 * 这样对比，是不是更能直观感觉到 Vue 3 的“数学解法”比 Vue 2 的“巡视员解法”更高级了？
 */


