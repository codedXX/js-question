/**
 * 注意点：
 * 1.排序的轮数为数组长度-1，因为每轮排序能确定一个元素的最终位置，6 轮确定 6 个，剩下那 1 个没地方去，自然也就对了。
 * 2.因为已经排好的元素不需要再参与比较，所以内层循环的范围会越来越短
 */
function bubbleSort(arr) {
  const n = arr.length;
  for (let i = 0; i < n - 1; i++) {
    for (let j = 0; j < n - 1 - i; j++) {
      if (arr[j] > arr[j + 1]) {
        let temp = arr[j];
        arr[j] = arr[j + 1];
        arr[j + 1] = temp;
      }
    }
  }
  return arr;
}

// 例子：对学生成绩排序，找出排名
const scores = [78, 92, 55, 88, 73, 95, 61];
console.log("原始成绩：", scores);

// bubbleSort([78, 92, 55, 88, 73, 95, 61]) 的完整计算过程：
//
// 第1轮(i=0)：最大值95冒到末尾
//   78 < 92  不动
//       92 > 55  交换 → [78, 55, 92, 88, 73, 95, 61]
//           92 > 88  交换 → [78, 55, 88, 92, 73, 95, 61]
//               92 > 73  交换 → [78, 55, 88, 73, 92, 95, 61]
//                   92 < 95  不动
//                       95 > 61  交换 → [78, 55, 88, 73, 92, 61, 95] ✓
//
// 第2轮(i=1)：92冒到倒数第二
//   78 > 55  交换 → [55, 78, 88, 73, 92, 61, 95]
//       78 < 88  不动
//           88 > 73  交换 → [55, 78, 73, 88, 92, 61, 95]
//               88 < 92  不动
//                   92 > 61  交换 → [55, 78, 73, 88, 61, 92, 95] ✓
//
// 第3轮(i=2)：88到位
//   55 < 78  不动
//       78 > 73  交换 → [55, 73, 78, 88, 61, 92, 95]
//           78 < 88  不动
//               88 > 61  交换 → [55, 73, 78, 61, 88, 92, 95] ✓
//
// 第4轮(i=3)：78到位
//   55 < 73  不动
//       73 < 78  不动
//           78 > 61  交换 → [55, 73, 61, 78, 88, 92, 95] ✓
//
// 第5轮(i=4)：73到位
//   55 < 73  不动
//       73 > 61  交换 → [55, 61, 73, 78, 88, 92, 95] ✓
//
// 第6轮(i=5)：确认最后两个
//   55 < 61  不动 ✓
//
// 最终结果：[55, 61, 73, 78, 88, 92, 95]
const sorted = bubbleSort([...scores]);
console.log("从低到高：", sorted);
console.log("最低分：", sorted[0]);
console.log("最高分：", sorted[sorted.length - 1]);
console.log("中位数：", sorted[Math.floor(sorted.length / 2)]);
